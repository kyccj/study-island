    if (!pool.length) return null;
    const w = pool.map((s) => RARITY_W[s.r] * (s.r >= 3 ? 1 + luck : 1) * (RARE_ONLY[s.id] || 1));
    let x = rng() * w.reduce((a, b) => a + b, 0);
    for (let i = 0; i < pool.length; i++) { x -= w[i]; if (x <= 0) return pool[i]; }
